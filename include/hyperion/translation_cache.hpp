#ifndef HYPERION_TRANSLATION_CACHE_HPP
#define HYPERION_TRANSLATION_CACHE_HPP

#include <cstddef>
#include <cstdint>
#include <memory>
#include <unordered_map>
#include <vector>

#include "hyperion/exec_mem.hpp"
#include "hyperion/interpreter.hpp"
#include "hyperion/run.hpp"
#include "hyperion/syscall.hpp"
#include "hyperion/translator.hpp"

namespace hyperion {

struct CachedBlock {
    void* entry = nullptr;
    BlockExit exit = BlockExit::kFallThrough;
    std::uint64_t start = 0;
    std::uint64_t target = 0;
    std::size_t guest_instruction_count = 0;
    std::size_t code_bytes = 0;
};

class TranslationCache {
public:
    TranslationCache();
    ~TranslationCache() = default;
    TranslationCache(const TranslationCache&) = delete;
    TranslationCache& operator=(const TranslationCache&) = delete;

    RunResult run(Memory& memory, GuestState state, std::uint64_t max_steps = 1'000'000,
                  SyscallHandler* syscalls = nullptr);

    std::size_t block_count() const { return blocks_.size(); }
    std::uint64_t dispatch_hits() const { return dispatch_hits_; }
    std::uint64_t dispatch_misses() const { return dispatch_misses_; }
    std::size_t translation_count() const { return blocks_.size(); }
    std::size_t total_code_bytes() const;

    // --- translation cost ---------------------------------------------------
    // Wall time spent inside translate_at() on the miss path, and the guest
    // instructions / generated bytes that time bought. Measured on the miss
    // path only, so accounting never appears in the hot path. These answer
    // "what does translation cost", which the per-instruction benchmarks in
    // benchmarks/tier_bench.cpp deliberately do not: a short guest pays this
    // once and a long one amortises it away.
    //
    // Caveats, stated rather than implied: this is wall time on the host, it
    // includes arena allocation and the W^X mprotect pair (see exec_mem.cpp),
    // and it is not comparable across machines.
    std::uint64_t translation_ns() const { return translation_ns_; }
    std::uint64_t translated_guest_instructions() const { return translated_guest_instructions_; }

    void invalidate_all();

private:
    enum class TranslateFailure : std::uint8_t { kNone, kFault, kUnsupported };

    void ensure_trampolines();
    const CachedBlock* translate_at(Memory& memory, std::uint64_t pc, TranslateFailure& failure);
    const CachedBlock* lookup(std::uint64_t pc);
    void install(const CachedBlock* block);

    ExecArena arena_;
    std::unique_ptr<ExecContext> ctx_;
    void* jit_entry_ = nullptr;
    void* jit_dispatch_ = nullptr;
    std::unordered_map<std::uint64_t, std::unique_ptr<CachedBlock>> blocks_;

    static constexpr std::size_t kDirectBits = 12; // 4096 slots
    static constexpr std::size_t kDirectSize = 1u << kDirectBits;
    static constexpr std::size_t kDirectMask = kDirectSize - 1;
    std::vector<const CachedBlock*> direct_{kDirectSize, nullptr};
    std::uint64_t dispatch_hits_ = 0;
    std::uint64_t dispatch_misses_ = 0;
    std::uint64_t cached_epoch_ = 0;     // code/SMC epoch: invalidates translations
    std::uint64_t cached_map_epoch_ = 0; // mapping generation: invalidates the data SoftTlb

    std::uint64_t translation_ns_ = 0;
    std::uint64_t translated_guest_instructions_ = 0;

    std::vector<std::uint8_t> fetch_;
};

} // namespace hyperion

#endif // HYPERION_TRANSLATION_CACHE_HPP
